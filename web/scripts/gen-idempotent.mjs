// Generates src/api/idempotent.gen.ts from the bundled OpenAPI document: every operation tagged
// `x-idempotent: required` becomes a "METHOD /path/template" key, so the client middleware throws
// in development when a call forgets its Idempotency-Key (web plan §6).
//
//   node scripts/gen-idempotent.mjs           write src/api/idempotent.gen.ts
//   node scripts/gen-idempotent.mjs --check   exit 1 when the committed file is out of date
//
// The bundle is machine-written and regular (paths at 2 spaces, methods at 4, operation keys at
// 6), so a line scan is enough and no YAML dependency is needed.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const SOURCE = resolve(here, '../../api/openapi-draft.yaml')
const TARGET = resolve(here, '../src/api/idempotent.gen.ts')
const METHODS = new Set(['get', 'put', 'post', 'patch', 'delete'])

export function extractIdempotent(text) {
  const found = new Set()
  let inPaths = false
  let path = null
  let method = null
  for (const line of text.split(/\r?\n/)) {
    if (/^\S/.test(line)) {
      inPaths = line.startsWith('paths:')
      path = method = null
      continue
    }
    if (!inPaths) continue
    let m = /^ {2}(\/\S*):\s*$/.exec(line)
    if (m) {
      path = m[1]
      method = null
      continue
    }
    m = /^ {4}([a-z]+):\s*$/.exec(line)
    if (m) {
      method = METHODS.has(m[1]) ? m[1] : null
      continue
    }
    if (path && method && /^ {6}x-idempotent:\s*required\s*$/.test(line)) {
      found.add(`${method.toUpperCase()} ${path}`)
    }
  }
  return [...found].sort()
}

export function render(keys) {
  return `// GENERATED by scripts/gen-idempotent.mjs from api/openapi-draft.yaml. Do not edit.
// Run \`pnpm gen:idempotent\` after the contract changes; a test fails when this file is stale.

/** Operations tagged \`x-idempotent: required\`, as "METHOD /path/template" keys. */
export const idempotentOperations: ReadonlySet<string> = new Set<string>([
${keys.map((k) => `  '${k}',`).join('\n')}
])
`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const keys = extractIdempotent(readFileSync(SOURCE, 'utf8'))
  const out = render(keys)
  if (process.argv.includes('--check')) {
    const current = readFileSync(TARGET, 'utf8')
    if (current.replace(/\r\n/g, '\n') !== out) {
      console.error('src/api/idempotent.gen.ts is out of date: run `pnpm gen:idempotent`')
      process.exit(1)
    }
    console.log(`idempotent.gen.ts is current (${keys.length} operations)`)
  } else {
    writeFileSync(TARGET, out)
    console.log(`wrote ${keys.length} operations to src/api/idempotent.gen.ts`)
  }
}
